function switchToItalian() {
    console.log('Switching to Italian...');
    
    // Translate all text nodes directly without storing
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );
    
    let node;
    let translatedCount = 0;
    
    while (node = walker.nextNode()) {
        const originalText = node.textContent;
        if (originalText.trim() && !originalText.includes('http') && !originalText.includes('data:') && !originalText.includes('data:image')) {
            // Check if text contains Russian characters
            if (/[а-яА-ЯЁё]/.test(originalText)) {
                let translatedText = originalText;
                for (const [russian, italian] of Object.entries(italianTranslations)) {
                    // Try exact match first
                    if (translatedText === russian) {
                        translatedText = italian;
                        break;
                    }
                    // Then try case-insensitive replace
                    translatedText = translatedText.replace(new RegExp(russian.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), italian);
                }
                
                if (translatedText !== originalText) {
                    originalTexts.set(node, originalText);
                    node.textContent = translatedText;
                    translatedCount++;
                }
            }
        }
    }
    
    console.log(`Translated ${translatedCount} text nodes`);
    alert(`Переведено ${translatedCount} элементов на итальянский!`);
    
    // Show restore button
    document.getElementById('italianRestoreBtn').style.display = 'block';
}

function restoreRussian() {
    // Restore original texts
    originalTexts.forEach((originalText, node) => {
        node.textContent = originalText;
    });

    // Clear the map
    originalTexts.clear();

    // Hide restore button
    document.getElementById('italianRestoreBtn').style.display = 'none';
}
